class AppStore {
	activeView = $state<ViewId>('mods');
	statusToast = $state('');
	discovery = $state<DiscoveryData | null>(null);
	grmlIni = $state<Record<string, Record<string, string>>>({});
	vfs = $state<VfsState>({
		enabled: true,
		scanWorkshop: true,
		indexedFiles: 0,
		conflictCount: 0,
		packs: [],
		conflicts: []
	});
	logTail = $state<string[]>([]);
	playlists = $state<PlaylistEntry[]>([]);
	selectedModId = $state<string | null>(null);

	// Settings state
	gameExeInput = $state('');
	chkWorkshop = $state(true);
	chkWip = $state(true);
	chkMenuStatus = $state(true);
	chkSkipIntro = $state(true);
	chkVfsEnabled = $state(true);
	overlayHotkey = $state('F9');

	// Saves state
	savesData = $state<SavesResponse | null>(null);
	savesLoading = $state(false);
	selectedSaveName = $state<string | null>(null);
	latestSave = $state('');

	// Diagnostics & crash banner state
	diagData = $state<DiagnosticsData | null>(null);
	lastCrashSaveName = $state('');
	crashBannerVisible = $state(false);
	launchWatchUntil = $state(0);
	launching = $state(false);

	// Update check state
	updateInfo = $state<UpdateCheckInfo | null>(null);
	checkingUpdate = $state(false);
	offsetsOtaResult = $state<OffsetsOtaResult | null>(null);
	updatingOffsets = $state(false);

	private diagPollInFlight = false;
	private diagTimer: ReturnType<typeof setInterval> | null = null;
	private getDiagAutoRefresh: () => boolean = () => false;
	private latestSavePollInFlight = false;

	get launchLocked(): boolean {
		return isLaunchLocked(this.launching, this.diagData?.running);
	}

	setStatus(msg: string) {
		this.statusToast = msg;
	}

	switchView(view: ViewId) {
		this.activeView = view;
		if (view === 'diagnostics') {
			this.pollDiagnostics(false, true);
		} else if (view === 'saves' && !this.savesData) {
			this.fetchSaves();
		}
	}

	async fetchState() {
		this.setStatus(t('status.discovering'));
		const qs = this.gameExeInput.trim()
			? `?game=${encodeURIComponent(this.gameExeInput.trim())}`
			: '';
		const resp = await fetch(`/api/state${qs}`);
		const data = await resp.json();
		if (data.error) {
			this.setStatus(`Error: ${data.error}`);
			return;
		}
		this.discovery = data.discovery;
		this.latestSave = data.latestSave ?? '';
		this.grmlIni = data.grmlIni ?? data.discovery?.grmlIni ?? {};
		this.vfs = data.vfs ?? data.discovery?.vfs ?? this.vfs;
		this.logTail = data.logTail ?? [];
		this.playlists = data.playlists ?? [];

		if (!this.gameExeInput && data.discovery?.gameExe) {
			this.gameExeInput = data.discovery.gameExe;
		}
		const gen = this.grmlIni.general ?? {};
		await i18n.init(gen.language, data.discovery?.gameLanguage ?? '');
		this.chkMenuStatus = gen.show_menu_status !== '0';
		this.chkSkipIntro = gen.skip_intro_logos !== '0';
		this.chkWorkshop = gen.scan_workshop !== '0';
		this.chkWip = gen.scan_workshop_wip !== '0';
		this.chkVfsEnabled = this.vfs.enabled !== false;
		this.overlayHotkey = (gen.overlay_hotkey || 'F9').trim() || 'F9';

		this.setStatus(t('status.loadedMods', { count: data.discovery?.mods?.length ?? 0 }));
	}

	async refreshLatestSave() {
		if (this.latestSavePollInFlight) return;
		this.latestSavePollInFlight = true;
		try {
			const qs = this.gameExeInput.trim()
				? `?game=${encodeURIComponent(this.gameExeInput.trim())}`
				: '';
			const resp = await fetch(`/api/latest-save${qs}`);
			if (!resp.ok) return;
			const data = await resp.json();
			const next = data.latestSave ?? '';
			if (next !== this.latestSave) {
				this.latestSave = next;
			}
		} catch {
			// Ignore transient poll errors while server shuts down
		} finally {
			this.latestSavePollInFlight = false;
		}
	}

	async saveGrmlIni() {
		if (!this.discovery) return;
		const plugins: Record<string, boolean> = {};
		for (const m of this.discovery.mods) {
			plugins[m.id] = m.enabled;
		}
		const general = {
			game_path: this.gameExeInput.trim(),
			show_menu_status: this.chkMenuStatus ? '1' : '0',
			skip_intro_logos: this.chkSkipIntro ? '1' : '0',
			scan_workshop: this.chkWorkshop ? '1' : '0',
			scan_workshop_wip: this.chkWip ? '1' : '0',
			overlay_hotkey: this.overlayHotkey || 'F9',
			language: i18n.setting || 'auto'
		};
		const resp = await fetch('/api/config', {
			method: 'POST',
			headers: { 'content-type': 'application/json' },
			body: JSON.stringify({ general, plugins })
		});
		if ((await resp.json()).ok) {
			this.setStatus(t('status.savedGrmlIni'));
		}
	}

	async saveVfsConfig() {
		const enabledMap: Record<string, boolean> = {};
		const orderedIds = this.vfs.packs.map((p) => {
			enabledMap[p.id] = Boolean(p.enabled);
			return p.id;
		});
		const resp = await fetch('/api/vfs', {
			method: 'POST',
			headers: { 'content-type': 'application/json' },
			body: JSON.stringify({
				enabled: this.chkVfsEnabled,
				orderedIds,
				enabledMap
			})
		});
		if ((await resp.json()).ok) {
			this.setStatus(t('status.savedVfsIni'));
			await this.fetchState();
		}
	}

	async fetchSaves(preselectName: string | null = null) {
		this.savesLoading = true;
		this.setStatus(t('status.scanningSaves'));
		try {
			const qs = this.gameExeInput.trim()
				? `?game=${encodeURIComponent(this.gameExeInput.trim())}`
				: '';
			const resp = await fetch(`/api/saves${qs}`);
			const data = (await resp.json()) as SavesResponse;
			this.savesData = data;
			if (!data.ok) {
				this.setStatus(`Save scan failed: ${data.error || 'Unknown error'}`);
				return;
			}
			if (preselectName) {
				this.selectedSaveName = preselectName;
			} else if (
				this.selectedSaveName &&
				!(data.saves || []).some((s) => s.name === this.selectedSaveName)
			) {
				this.selectedSaveName = null;
			}
			if (!this.selectedSaveName && (data.saves || []).length > 0) {
				this.selectedSaveName = data.saves[0].name;
			}
			this.setStatus(t('status.scannedSaves', { count: (data.saves || []).length }));
		} finally {
			this.savesLoading = false;
		}
	}

	async pollDiagnostics(checkEvents = false, checkProcess = false) {
		if (this.diagPollInFlight) return;
		this.diagPollInFlight = true;
		try {
			const params = new URLSearchParams();
			if (checkEvents) params.set('checkEvents', '1');
			if (checkProcess || checkEvents) params.set('checkProcess', '1');
			const qs = params.toString() ? `?${params.toString()}` : '';
			const resp = await fetch(`/api/diagnostics${qs}`);
			if (!resp.ok) return;
			const data = (await resp.json()) as DiagnosticsData;
			this.diagData = data;
			if (data.exitedUnexpectedly) {
				this.launchWatchUntil = 0;
				const crashItem = (data.suspects || []).find((s) => s.severity === 'crash');
				if (crashItem) {
					this.setStatus(`Crash detected: ${crashItem.modName} — ${crashItem.reason}`);
				}
				if (data.crashDetected && data.lastLoadedSave) {
					this.lastCrashSaveName = data.lastLoadedSave;
					this.crashBannerVisible = true;
				}
			}
		} catch {
			// ignore transient poll error
		} finally {
			this.diagPollInFlight = false;
		}
	}

	startDiagnosticsPolling(getAutoRefresh?: () => boolean) {
		if (getAutoRefresh) this.getDiagAutoRefresh = getAutoRefresh;
		if (this.diagTimer) return;
		this.diagTimer = setInterval(() => {
			if (shouldPollProcess(this.launchWatchUntil, this.diagData?.running)) {
				this.pollDiagnostics(false, true);
			} else if (this.activeView === 'diagnostics' && this.getDiagAutoRefresh()) {
				this.pollDiagnostics(false, false);
			}
		}, 5000);
	}

	async checkForUpdates(manual = false) {
		if (this.checkingUpdate) return;
		this.checkingUpdate = true;
		if (manual) this.setStatus(t('status.checkingUpdates'));
		try {
			const resp = await fetch('/api/check-update');
			const data = (await resp.json()) as UpdateCheckInfo;
			this.updateInfo = data;
			if (manual) {
				if (!data.ok) {
					this.setStatus(`Update check failed: ${data.error || 'Offline'}`);
				} else if (data.updateAvailable) {
					this.setStatus(t('status.updateAvailable', { version: data.latestVersion ?? '' }));
				} else {
					this.setStatus(t('status.upToDate', { version: data.currentVersion }));
				}
			}
		} catch {
			if (manual) this.setStatus(t('status.updateCheckOffline'));
		} finally {
			this.checkingUpdate = false;
		}
	}

	async updateOffsetsOta() {
		if (this.updatingOffsets) return;
		this.updatingOffsets = true;
		this.setStatus(t('status.fetchingOffsets'));
		try {
			const resp = await fetch('/api/update-offsets', { method: 'POST' });
			const data = (await resp.json()) as OffsetsOtaResult;
			this.offsetsOtaResult = data;
			if (!data.ok) {
				this.setStatus(`Offsets OTA failed: ${data.error || 'Unknown error'}`);
				return;
			}
			await this.fetchState();
			if (data.updated) {
				this.setStatus(t('status.offsetsUpdated', { count: data.entryCount ?? 0, hash: data.hash ?? '' }));
			} else {
				this.setStatus(t('status.offsetsAlreadyUpToDate', { hash: data.hash ?? '' }));
			}
		} catch {
			this.offsetsOtaResult = { ok: false, error: 'Network error' };
			this.setStatus(t('status.offsetsOtaOffline'));
		} finally {
			this.updatingOffsets = false;
		}
	}

	async launchWrsr(autoLoadSave?: string | null, tempDisabledIds?: string[]) {
		await runGuardedLaunch({
			isLocked: () => this.launchLocked,
			setLaunching: (v) => {
				this.launching = v;
			},
			saveIni: () => this.saveGrmlIni(),
			setStatus: (msg) => this.setStatus(msg),
			fetchFn: fetch,
			gameExe: this.gameExeInput,
			autoLoadSave: autoLoadSave || undefined,
			tempDisabledIds,
			launchingStatus: autoLoadSave
				? t('status.launchingIntoSave', { save: autoLoadSave })
				: t('status.launching'),
			launchedStatus: t('status.launched'),
			launchFailedStatus: t('status.launchFailed'),
			onLaunchSuccess: async () => {
				this.launchWatchUntil = Date.now() + 30000;
				this.diagData = {
					...(this.diagData ?? {
						running: true,
						pids: [],
						lastLaunchPid: null,
						exitedUnexpectedly: false,
						logTail: [],
						suspects: [],
						checkedAt: ''
					}),
					running: true
				};
				await this.pollDiagnostics(false, true);
			}
		});
	}
}

export const app = new AppStore();
